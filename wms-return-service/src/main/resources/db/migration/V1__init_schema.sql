CREATE TABLE IF NOT EXISTS wms_return_order (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    return_no VARCHAR(64) NOT NULL,
    source_system VARCHAR(16) DEFAULT NULL,
    source_no VARCHAR(64) DEFAULT NULL,
    warehouse_code VARCHAR(64) NOT NULL,
    sku_code VARCHAR(64) NOT NULL,
    batch_no VARCHAR(64) DEFAULT NULL,
    qty DECIMAL(18,3) NOT NULL,
    disposition VARCHAR(16) DEFAULT NULL COMMENT 'SALEABLE / DEFECT / SCRAP',
    status VARCHAR(16) NOT NULL COMMENT 'CREATED / INSPECTED / IN_STOCK / SCRAPPED',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uk_return_no (return_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='退货单';
